/**
 * i18n.js — Internationalisation strings
 * ========================================
 * All user-visible strings for the three supported languages:
 *   en  English (default)
 *   ja  Japanese
 *   zh  Simplified Chinese
 *
 * USAGE
 * -----
 * import { getTranslations } from "./i18n";
 * const t = getTranslations("en");
 * // then use t.scrape, t.save, t.generateCard, etc.
 *
 * STRUCTURE
 * ---------
 * Each language is a flat object. Keys are camelCase English names.
 * Nested objects are used for grouped keys (e.g. t.fields.description,
 * t.entryTypes.concept).
 *
 * HOW TO ADD A NEW STRING
 * -----------------------
 * 1. Add the key to the `en` object with the English value.
 * 2. Add the same key to `ja` and `zh` with translations.
 * 3. Use it in components as: t.myNewKey || "fallback"
 *    (the fallback protects against missing keys during development)
 *
 * HOW TO ADD A NEW LANGUAGE
 * -------------------------
 * 1. Add a new object (e.g. `ko`) with all the same keys as `en`.
 * 2. Add the language option to the TopNav language selector.
 * 3. The getTranslations() function will return it automatically.
 */

